import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

import { verifyStylesheet } from "./verify-styles.mjs";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageManifest = JSON.parse(
  readFileSync(resolve(packageRoot, "package.json"), "utf8"),
);
const isWindows = process.platform === "win32";
const npmCommand = isWindows ? "npm.cmd" : "npm";
const result = spawnSync(
  npmCommand,
  ["pack", "--dry-run", "--json", "--ignore-scripts"],
  {
    cwd: packageRoot,
    encoding: "utf8",
    shell: isWindows,
  },
);

if (result.error) {
  console.error(`Failed to start npm pack with ${npmCommand}:`);
  console.error(result.error);
  process.exit(1);
}

const stdout = result.stdout ?? "";
const stderr = result.stderr ?? "";

if (result.status !== 0) {
  process.stderr.write(
    stderr || stdout || `npm pack exited with status ${result.status ?? "unknown"}\n`,
  );
  process.exit(result.status ?? 1);
}

assert.ok(stdout.trim(), "npm pack returned no JSON output");

let reports;
try {
  reports = JSON.parse(stdout);
} catch (error) {
  console.error("npm pack returned invalid JSON:");
  console.error(stdout);
  throw error;
}

const report = reports.at(-1);
assert.ok(report, "npm pack returned no package report");
assert.equal(report.name, packageManifest.name);
assert.equal(report.version, packageManifest.version);

const files = new Set(report.files.map((file) => file.path));
const required = [
  "package.json",
  "README.md",
  "LICENSE",
  "dist/index.js",
  "dist/index.d.ts",
  "dist/vite.js",
  "dist/vite.d.ts",
  "dist/virtual.d.ts",
  "dist/styles.css",
];

for (const path of required) {
  assert.ok(files.has(path), `npm package is missing ${path}`);
}

// File existence is not enough for the stylesheet: it is generated by the
// ordered aggregation in styles/manifest.mjs and must still carry the frozen
// tokens, global rules, component/static selectors and cascade order. The
// packed artifact must also contain exactly the built aggregated bytes.
const styles = verifyStylesheet({ packageRoot });
if (styles.failures.length > 0) {
  for (const failure of styles.failures) {
    console.error(`[${failure.id}] FAIL ${failure.message}`);
  }
  console.error(
    `dist/styles.css failed ${styles.failures.length} content check(s); ` +
      "fix styles/manifest.mjs or the stylesheet, then rebuild",
  );
  process.exit(1);
}
const packedStyles = report.files.find((file) => file.path === "dist/styles.css");
assert.equal(
  packedStyles?.size,
  styles.bytes,
  "the packed dist/styles.css size does not match the built aggregated stylesheet",
);
console.log(
  `styles.css verified: ${styles.sources.length} ordered source(s), ${styles.bytes} bytes, tokens + global rules + component/static selectors + cascade order`,
);

// The declaration must be reachable from both publicly exported type files,
// not merely present as an otherwise undiscoverable file in the archive.
for (const name of ["index.d.ts", "vite.d.ts"]) {
  const types = readFileSync(resolve(packageRoot, "dist", name), "utf8");
  assert.ok(
    types.startsWith('/// <reference path="./virtual.d.ts" />'),
    `dist/${name} does not reference the packaged virtual module declaration`,
  );
}
assert.ok(
  readFileSync(resolve(packageRoot, "dist/virtual.d.ts"), "utf8")
    .includes('declare module "virtual:folio/content"'),
  "dist/virtual.d.ts does not declare the Folio content module",
);

for (const path of files) {
  assert.ok(!path.startsWith("src/"), `source file leaked into package: ${path}`);
  assert.ok(!path.startsWith("test/"), `test file leaked into package: ${path}`);
}

console.log(
  `npm pack verified: ${report.filename}, ${report.entryCount} files, ${report.unpackedSize} bytes unpacked`,
);
